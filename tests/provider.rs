use ghenv::provider::{self, Context, PrivateKey, Project, Request, Values};
use serde_json::{Value, json};
use std::{fs, time::Duration};
const ID: &str = "0123456789abcdef0123456789abcdef";
const BUNDLE: &str = r#"{"version":1,"environment":"Preview","repository":"owner/repo","secrets":{"TOKEN":"synthetic secret"},"variables":{"URL":"http://localhost"}}"#;
const PROFILE: &str = r#"{"version":1,"repository":"owner/project","default_mode":"preview","secrets":"API_KEY","variables":"PUBLIC_KEY","prefixes":{"API_KEY":"test_"},"aliases":{"PUBLIC_ALIAS":"PUBLIC_KEY"},"environment":{"BUN_OPTIONS":"--no-env-file"}}"#;
fn key() -> PrivateKey {
    PrivateKey::from_pkcs8(include_bytes!("fixtures/test-key.p8")).unwrap()
}
fn profile(text: &str) -> provider::Result<Project> {
    let root = tempfile::tempdir()?;
    let path = root.path().join("ghenv.json");
    fs::write(&path, text)?;
    Project::read(path)
}
#[test]
fn go_envelope_and_rust_envelope_share_the_v1_protocol() {
    // This published, disposable test key and envelope were generated by the
    // original Go provider. They contain only the synthetic values below.
    let key = key();
    let expected = Values::from([
        ("TOKEN".into(), "synthetic line\n'quoted' $()=😀".into()),
        ("EMPTY".into(), String::new()),
    ]);
    let values = provider::unseal(&key, include_bytes!("fixtures/go-payload.json"), ID).unwrap();
    assert_eq!(values, expected);
    let payload = provider::seal(&key.public_key().unwrap(), &expected, ID).unwrap();
    assert_eq!(provider::unseal(&key, &payload, ID).unwrap(), expected);
    assert!(!String::from_utf8_lossy(&payload).contains("synthetic line"));
    if let Ok(path) = std::env::var("GHENV_INTEROP_OUTPUT") {
        fs::write(path, &payload).unwrap();
    }
    assert!(provider::unseal(&key, &payload, "different-request").is_err());
    let other = PrivateKey::generate().unwrap();
    assert!(provider::unseal(&other, &payload, ID).is_err());
    for field in ["nonce", "key", "ciphertext", "version"] {
        let mut bad: Value = serde_json::from_slice(&payload).unwrap();
        bad[field] = "bad".into();
        assert!(provider::unseal(&key, &serde_json::to_vec(&bad).unwrap(), ID).is_err());
    }
    assert!(provider::seal("bad-key", &expected, ID).is_err());
}
#[test]
fn bundle_scope_types_ambiguity_and_selection_are_checked_before_export() {
    let key = key();
    let public = key.public_key().unwrap();
    let payload =
        provider::seal_bundle(BUNDLE.as_bytes(), "owner/repo", "TOKEN", "URL", &public, ID)
            .unwrap();
    assert_eq!(
        provider::unseal(&key, &payload, ID).unwrap(),
        Values::from([
            ("TOKEN".into(), "synthetic secret".into()),
            ("URL".into(), "http://localhost".into())
        ])
    );
    let mut invalid = vec![
        String::new(),
        "null".into(),
        "{}".into(),
        format!("{BUNDLE}{BUNDLE}"),
        " ".repeat((48 << 10) + 1),
    ];
    for (from, to) in [
        ("\"Preview\"", "\"Production\""),
        ("\"owner/repo\"", "\"owner/other\""),
        ("\"version\":1", "\"version\":2"),
        ("\"version\":1", "\"version\":1,\"version\":1"),
        ("\"version\":1", "\"version\":1,\"Version\":1"),
        ("\"version\":1", "\"version\":1,\"unexpected\":true"),
        ("\"URL\":\"http://localhost\"", "\"TOKEN\":\"duplicate\""),
        ("\"TOKEN\"", "\"GITHUB_TOKEN\""),
        ("\"TOKEN\"", "\"INVALID-NAME\""),
        ("\"synthetic secret\"", "\"bad\\u0000value\""),
        ("\"synthetic secret\"", "42"),
        ("\"synthetic secret\"", "null"),
        ("\"http://localhost\"", "null"),
        (
            "\"secrets\":{\"TOKEN\":\"synthetic secret\"}",
            "\"secrets\":null",
        ),
        (
            "\"variables\":{\"URL\":\"http://localhost\"}",
            "\"variables\":null",
        ),
        ("\"secrets\"", "\"ſecrets\""),
        ("\"repository\"", "\"repoſitory\""),
        ("\"version\":1", "\"Version\":1"),
        (
            "\"secrets\":",
            "\"ſecrets\":{\"EXTRA\":\"sentinel\"},\"secrets\":",
        ),
        (",\"variables\":{\"URL\":\"http://localhost\"}", ""),
    ] {
        invalid.push(BUNDLE.replacen(from, to, 1));
    }
    for data in invalid {
        assert!(
            provider::seal_bundle(data.as_bytes(), "owner/repo", "TOKEN", "URL", &public, ID)
                .is_err()
        );
    }
    for (secrets, variables) in [
        ("MISSING", ""),
        ("TOKEN", "TOKEN"),
        ("GITHUB_TOKEN", ""),
        ("github_token", ""),
        ("TOKEN,", ""),
        ("BAD-NAME", ""),
        ("", ""),
    ] {
        assert!(
            provider::seal_bundle(
                BUNDLE.as_bytes(),
                "owner/repo",
                secrets,
                variables,
                &public,
                ID
            )
            .is_err()
        );
    }
    assert!(provider::seal_bundle(BUNDLE.as_bytes(), "", "TOKEN", "URL", &public, ID).is_err());
    assert!(
        provider::seal_bundle(
            BUNDLE.as_bytes(),
            "owner/repo",
            "TOKEN",
            "URL",
            &public,
            "bad"
        )
        .is_err()
    );
}
#[test]
fn public_request_validation_refuses_unsupported_scope_and_names() {
    let valid = Request {
        repo: "owner/repo".into(),
        environment: "Preview".into(),
        reference: "main".into(),
        secrets: "TOKEN".into(),
        variables: "URL".into(),
    };
    assert!(valid.validate().is_ok());
    for (field, value) in [
        ("repo", "../repo"),
        ("repo", "owner/.."),
        ("repo", "owner/other/extra"),
        ("environment", "Production"),
        ("environment", ""),
        ("reference", ""),
        ("secrets", "GITHUB_TOKEN"),
        ("secrets", "URL"),
    ] {
        let mut request = valid.clone();
        match field {
            "repo" => request.repo = value.into(),
            "environment" => request.environment = value.into(),
            "reference" => request.reference = value.into(),
            _ => request.secrets = value.into(),
        }
        assert!(request.validate().is_err());
    }
}
#[test]
fn project_profiles_reject_ambiguous_policy_and_collisions() {
    assert!(profile(PROFILE).is_ok());
    for (from, to) in [
        ("\"version\":1", "\"version\":2"),
        (
            "\"default_mode\":\"preview\"",
            "\"default_mode\":\"Production\"",
        ),
        (
            "\"repository\":\"owner/project\"",
            "\"repository\":\"owner/..\"",
        ),
        ("\"secrets\":\"API_KEY\"", "\"secrets\":\"API_KEY,API_KEY\""),
        ("\"secrets\":\"API_KEY\"", "\"secrets\":\"GITHUB_TOKEN\""),
        ("\"API_KEY\":\"test_\"", "\"UNKNOWN\":\"test_\""),
        (
            "\"PUBLIC_ALIAS\":\"PUBLIC_KEY\"",
            "\"PUBLIC_ALIAS\":\"UNKNOWN\"",
        ),
        (
            "\"PUBLIC_ALIAS\":\"PUBLIC_KEY\"",
            "\"API_KEY\":\"PUBLIC_KEY\"",
        ),
        (
            "\"BUN_OPTIONS\":\"--no-env-file\"",
            "\"PUBLIC_ALIAS\":\"collision\"",
        ),
        (
            "\"BUN_OPTIONS\":\"--no-env-file\"",
            "\"API_KEY\":\"collision\"",
        ),
        ("\"version\":1", "\"version\":1,\"version\":1"),
        ("\"secrets\"", "\"Secrets\""),
        ("\"secrets\"", "\"ſecrets\""),
    ] {
        assert!(profile(&PROFILE.replacen(from, to, 1)).is_err());
    }
    for text in [
        "{}",
        "null",
        "[]",
        &format!("{PROFILE}{{}}"),
        &" ".repeat((48 << 10) + 1),
    ] {
        assert!(profile(text).is_err());
    }
}
#[test]
fn prepare_isolates_values_applies_prefixes_and_never_fetches_for_local_mode() {
    let project = profile(PROFILE).unwrap();
    let context = Context::new(Duration::from_secs(5)).unwrap();
    let base = Values::from([
        ("PATH".into(), "/tools".into()),
        ("GH_TOKEN".into(), "parent-secret".into()),
        ("API_KEY".into(), "parent".into()),
        ("BUN_OPTIONS".into(), "--preload=bad".into()),
        ("EXPO_NO_DOTENV".into(), "0".into()),
        ("REMOTE_DATABASE_URL".into(), "parent".into()),
        ("RUSTC_WRAPPER".into(), "untrusted".into()),
    ]);
    let selected = Values::from([
        ("API_KEY".into(), "test_synthetic\nquoted ' $()".into()),
        ("PUBLIC_KEY".into(), "public".into()),
    ]);
    let env = project
        .environment_with(&context, "auto", &base, |_, request| {
            assert_eq!(request.repo, "owner/project");
            assert_eq!(request.environment, "Preview");
            assert_eq!(request.reference, "main");
            Ok(selected.clone())
        })
        .unwrap();
    assert_eq!(env["API_KEY"], selected["API_KEY"]);
    assert_eq!(env["PUBLIC_ALIAS"], "public");
    assert_eq!(env["BUN_OPTIONS"], "--no-env-file");
    assert_eq!(env["EXPO_NO_DOTENV"], "1");
    for name in ["GH_TOKEN", "REMOTE_DATABASE_URL", "RUSTC_WRAPPER"] {
        assert!(!env.contains_key(name));
    }
    let offline = project
        .environment_with(&context, "local", &base, |_, _| {
            panic!("offline request contacted GitHub")
        })
        .unwrap();
    assert!(!offline.contains_key("API_KEY"));
    assert!(!offline.contains_key("PUBLIC_ALIAS"));
    let empty=profile(r#"{"version":1,"repository":"owner/project","default_mode":"local","environment":{"BUN_OPTIONS":"--no-env-file"}}"#).unwrap();
    assert!(
        empty
            .environment_with(&context, "preview", &base, |_, _| panic!(
                "empty selection contacted GitHub"
            ))
            .is_ok()
    );
    for values in [
        json!({"API_KEY":"live_do_not_print","PUBLIC_KEY":"public"}),
        json!({"API_KEY":"test_synthetic"}),
        json!({"API_KEY":"test_synthetic","PUBLIC_KEY":"public","OTHER":"do_not_print"}),
        json!({"API_KEY":"test_synthetic\u{0}do_not_print","PUBLIC_KEY":"public"}),
    ] {
        let error = project
            .environment_with(&context, "preview", &base, |_, _| {
                Ok(serde_json::from_value(values.clone()).unwrap())
            })
            .unwrap_err();
        assert!(!error.to_string().contains("do_not_print"));
    }
    assert!(
        project
            .environment_with(&context, "Production", &base, |_, _| panic!(
                "invalid mode contacted GitHub"
            ))
            .is_err()
    );
    assert!(
        project
            .environment_with(&context, "preview", &base, |_, _| Err(
                "handoff failed".into()
            ))
            .is_err()
    );
}
#[test]
fn context_deadline_and_explicit_cancellation_are_bounded() {
    let context = Context::new(Duration::ZERO).unwrap();
    assert!(context.check().is_err());
    let context = Context::new(Duration::from_secs(1)).unwrap();
    let clone = context.clone();
    clone.cancel();
    assert!(context.check().is_err());
}
